CREATE TABLE IF NOT EXISTS public.astro_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS astro_users_single_admin_idx
    ON public.astro_users ((role))
    WHERE role = 'admin';

CREATE TABLE IF NOT EXISTS public.login_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.astro_users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS login_sessions_expires_at_idx
    ON public.login_sessions (expires_at);

CREATE TABLE IF NOT EXISTS public.site_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL UNIQUE,
    title_en VARCHAR(180) NOT NULL,
    title_hi VARCHAR(180) NOT NULL,
    excerpt_en VARCHAR(500) NOT NULL,
    excerpt_hi VARCHAR(500) NOT NULL,
    content_en TEXT NOT NULL,
    content_hi TEXT NOT NULL,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.consultation_enquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquiry_type TEXT NOT NULL CHECK (enquiry_type IN ('consultation', 'contact')),
    user_id BIGINT REFERENCES public.astro_users(id) ON DELETE SET NULL,
    name VARCHAR(100) NOT NULL,
    mobile VARCHAR(25) NOT NULL,
    preferred_language VARCHAR(7) NOT NULL CHECK (preferred_language IN ('Hindi', 'English')),
    consultation_type VARCHAR(40),
    preferred_date DATE,
    preferred_time TIME,
    message VARCHAR(1000),
    privacy_consent BOOLEAN NOT NULL CHECK (privacy_consent IS TRUE),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT consultation_details_match_enquiry CHECK (
        (enquiry_type = 'consultation'
            AND consultation_type IN ('Kundli Analysis', 'Vedic Astrology Consultation', 'Spiritual Guidance', 'Vastu Consultation')
            AND preferred_date IS NOT NULL
            AND preferred_time IS NOT NULL)
        OR
        (enquiry_type = 'contact'
            AND consultation_type IS NULL
            AND preferred_date IS NULL
            AND preferred_time IS NULL)
    )
);

ALTER TABLE public.consultation_enquiries
    DROP CONSTRAINT IF EXISTS consultation_details_match_enquiry;

ALTER TABLE public.consultation_enquiries
    ADD CONSTRAINT consultation_details_match_enquiry CHECK (
        (enquiry_type = 'consultation'
            AND consultation_type IN ('Kundli Analysis', 'Vedic Astrology Consultation', 'Spiritual Guidance', 'Vastu Consultation')
            AND preferred_date IS NOT NULL
            AND preferred_time IS NOT NULL)
        OR
        (enquiry_type = 'contact'
            AND consultation_type IS NULL
            AND preferred_date IS NULL
            AND preferred_time IS NULL)
    );

ALTER TABLE public.consultation_enquiries
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES public.astro_users(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS consultation_enquiries_created_at_idx
    ON public.consultation_enquiries (created_at DESC);

CREATE TABLE IF NOT EXISTS public.astro_chat_consents (
    customer_id BIGINT PRIMARY KEY REFERENCES public.astro_users(id) ON DELETE CASCADE,
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.astro_chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES public.astro_users(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES public.astro_users(id) ON DELETE CASCADE,
    message VARCHAR(2000) NOT NULL CHECK (LENGTH(BTRIM(message)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS astro_chat_messages_customer_idx
    ON public.astro_chat_messages (customer_id, id DESC);

CREATE TABLE IF NOT EXISTS public.astro_customer_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL UNIQUE REFERENCES public.astro_users(id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    message VARCHAR(2000) NOT NULL CHECK (LENGTH(BTRIM(message)) >= 10),
    public_consent BOOLEAN NOT NULL CHECK (public_consent IS TRUE),
    is_public BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS astro_customer_feedback_public_idx
    ON public.astro_customer_feedback (created_at DESC)
    WHERE is_public = TRUE;
